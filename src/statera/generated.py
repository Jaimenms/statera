"""Single header for the files the framework generates that live in the content repository.

Every generated file starts with the same notice, in the comment syntax of its format. The notice says
the file is generated, by which command, from which sources, and how to change it. It is the "Code
generated ... DO NOT EDIT." convention (Go and many other tools). Besides the notice,
the content repository marks the same files in `.gitattributes` (`linguist-generated`) and in
VS Code (`files.readonlyInclude`), per specification 01.
"""

from __future__ import annotations

MARKER = "GENERATED FILE by the Statera framework. Do not edit by hand: the next generation undoes the change."


def lines(
    command: str, sources: str, *, regenerate: str = "statera sync", ci: bool = True, note: str | None = None
) -> list[str]:
    output = [
        MARKER,
        f"Generated by `{command}`. Sources: {sources}.",
        f"To change it: edit the sources and run `{regenerate}`."
        + (" CI fails if this file is out of date." if ci else ""),
    ]
    return output + (note.splitlines() if note else [])


def header(command: str, sources: str, *, style: str = "#", **options) -> str:
    """The notice as a comment: `#` (YAML, CODEOWNERS), `%%` (Mermaid), `xml` (XML, SVG, HTML), `md`."""
    text = lines(command, sources, **options)
    if style in ("#", "%%"):
        return "".join(f"{style} {line}\n" for line in text)
    if style == "xml":
        return "<!--\n" + "".join(f"  {line}\n" for line in text) + "-->\n"
    if style == "md":
        return "> " + "  \n> ".join(text) + "\n"
    raise ValueError(f"unknown comment style: {style}")


def as_html(document: str, xml_header: str) -> str:
    """Puts the notice right after `<!doctype html>`: before it, the browser switches to quirks mode."""
    doctype, separator, rest = document.partition("\n")
    if doctype.lower().startswith("<!doctype"):
        return doctype + separator + xml_header + rest
    return xml_header + document
