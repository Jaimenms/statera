"""How the public accesses each dissemination product: distributions and visualizations.

The data product is the DATA (output ports with a contract). What the public opens is:

- **distributions** (files), in DCAT vocabulary (`dcat:Distribution`):
    * product with a series: derived from `7-disseminate/series.yaml` and from the editions register
      (spreadsheet, tables, metadata of the latest published edition), with the page and the dataset on dados.gov.br;
    * product still produced outside the process (level 1): declared in the ODPS descriptor, under
      `customProperties.distributions`;
- **visualizations**: consumers declared as dbt `exposures`, with `meta.visualization`:
    * `dashboard`: BI dashboard (Power BI, Superset, Metabase…);
    * `chart`: static charts (PNG, SVG) published on the portal.

A public visualization (`sharing: broad`) reads the PUBLISHED EDITION, so it shows the same number
as the spreadsheet. A static chart declares, for each image, the alternative text and the output
port with the chart's numbers as a table (e-MAG; Lei 13.146/2015, art. 63; WCAG 1.1.1).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from statera import contracts, ports
from statera.project import Project, Unit

READS = ("published-edition", "cut-date", "current")
VISUALIZATIONS = ("dashboard", "chart")
DISTRIBUTION_FIELDS = ("title", "format", "url", "updated")
VISUALIZATION_FIELDS = ("product", "tool", "reads", "updated", "sharing")


@dataclass
class Distribution:
    title: str
    format_: str
    url: str | None = None
    updated: str = ""
    origin: str = "declared"  # "series" (generated by the process) or "declared" (ODPS)
    edition: str | None = None  # reference month of the latest published edition
    registry: Path | None = None  # Data Package of the latest edition, in the register
    ports: tuple[str, ...] = ()


# ---------------------------------------------------------------------------
# Distributions
# ---------------------------------------------------------------------------


def declared_distributions(unit: Unit) -> list[dict]:
    return contracts.custom_property_of(unit.odps, "distributions", []) or []


def distributions(unit: Unit) -> list[Distribution]:
    from statera.disseminate import registry

    output = []
    if unit.has("7-disseminate/series.yaml"):
        s = registry.series_config(unit)
        edition_files, page = s["files_per_edition"], s.get("page")
        editions = registry.editions(unit)
        latest = editions[-1]["x-statera"]["period"] if editions else None
        path = registry.edition_path(unit, latest) if latest else None
        port_names = tuple(p["name"] for p in ports.output_ports(unit))
        spreadsheet = edition_files["spreadsheet"].format(period=latest or "YYYY-MM")
        output += [
            Distribution(f"Spreadsheet ({spreadsheet})", "xlsx", page, s["frequency"], "series", latest, path,
                         port_names),
            Distribution(f"Tables ({len(port_names)} CSV files)", "csv", page, s["frequency"], "series",
                         latest, path, port_names),
        ]  # fmt: skip
        if gov := s.get("open_data_portal"):
            title = f"Open data portal (CKAN): dataset `{gov['dataset']}` ({gov['organization']})"
            output.append(Distribution(title, "CKAN", None, s["frequency"], "series", latest, path,
                                      port_names))  # fmt: skip
    for d in declared_distributions(unit):
        output.append(Distribution(d.get("title", ""), d.get("format", ""), d.get("url"), d.get("updated", ""),
                                  "declared", ports=tuple(d.get("ports", []))))  # fmt: skip
    return output


def distribution_problems(unit: Unit) -> list[str]:

    problems = []
    port_names = {p["name"] for p in ports.output_ports(unit)}
    for i, d in enumerate(declared_distributions(unit), 1):
        label = d.get("title") or f"distribution {i}"
        problems += [f"{label}: missing '{c}'" for c in DISTRIBUTION_FIELDS if not d.get(c)]
        problems += [f"{label}: port '{p}' does not exist" for p in d.get("ports", []) if p not in port_names]
    if not unit.internal and not unit.has("7-disseminate/series.yaml") and not declared_distributions(unit):
        problems.append("dissemination product with no means of access: series.yaml or customProperties.distributions")
    return problems


# ---------------------------------------------------------------------------
# Visualizations (exposures)
# ---------------------------------------------------------------------------


def visualizations(manifest: dict) -> list[dict]:
    return sorted(
        (e for e in manifest["exposures"].values() if (e.get("meta") or {}).get("visualization")),
        key=lambda e: e["name"],
    )


def visualization_problems(project: Project, e: dict) -> list[str]:
    meta, name = e.get("meta") or {}, e["name"]
    kind = meta.get("visualization")
    if kind not in VISUALIZATIONS:
        return [f"{name}: meta.visualization '{kind}' should be one of {list(VISUALIZATIONS)}"]
    problems = [f"{name}: missing meta.{c}" for c in VISUALIZATION_FIELDS if not meta.get(c)]
    if not e.get("url"):
        problems.append(f"{name}: missing url (where the public opens the visualization)")
    if meta.get("reads") and meta["reads"] not in READS:
        problems.append(f"{name}: meta.reads '{meta['reads']}' should be one of {list(READS)}")
    if meta.get("sharing") == "broad" and meta.get("reads") != "published-edition":
        problems.append(
            f"{name}: a public visualization must read the published edition (meta.reads: published-edition), "
            "so it shows the same number as the spreadsheet"
        )
    unit = next((u for u in project.products() if u.name == meta.get("product")), None)
    if meta.get("product") and unit is None:
        problems.append(f"{name}: product '{meta['product']}' does not exist")
    problems += [
        f"{name}: author without a name in meta.authors" for a in meta.get("authors") or [] if not a.get("name")
    ]
    if kind == "chart":
        charts = meta.get("charts") or []
        if not charts:
            problems.append(f"{name}: chart without meta.charts (title, port and alternative text of each image)")
        port_names = {p["name"] for p in ports.output_ports(unit)} if unit else set()
        for i, g in enumerate(charts, 1):
            label = g.get("title") or f"chart {i}"
            if not g.get("alt_text"):
                problems.append(f"{name} / {label}: missing alt_text (e-MAG, WCAG 1.1.1)")
            if g.get("port") not in port_names:
                problems.append(f"{name} / {label}: port '{g.get('port')}' is not an output of the product")
    return problems
